import AppKit

/// Polls the general pasteboard and turns new contents into `ClipItem`s.
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private let pb = NSPasteboard.general
    private var lastChange: Int
    private var timer: Timer?
    /// Change count produced by our own writes; skipped so pasting doesn't create duplicates.
    var ignoreChangeCount: Int?

    private init() { lastChange = NSPasteboard.general.changeCount }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.35, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer!, forMode: .common)
    }

    private func poll() {
        let count = pb.changeCount
        guard count != lastChange else { return }
        lastChange = count
        if count == ignoreChangeCount { return }
        let settings = AppSettings.shared
        if settings.isPaused { return }
        if settings.pausedUntil != nil { settings.pausedUntil = nil }

        let types = Set(pb.types ?? [])
        if settings.ignoreConfidential, types.contains(.init("org.nspasteboard.ConcealedType")) { return }
        if settings.ignoreTransient,
           types.contains(.init("org.nspasteboard.TransientType")) || types.contains(.init("org.nspasteboard.AutoGeneratedType")) { return }

        let app = NSWorkspace.shared.frontmostApplication
        if let bid = app?.bundleIdentifier, settings.ignoredApps.contains(bid) { return }

        guard var item = capture() else { return }
        item.appBundleID = app?.bundleIdentifier
        item.appName = app?.localizedName
        let id = ClipStore.shared.add(item)
        SoundFX.copy()
        if item.kind == .link { LinkPreviewer.shared.fetchIfNeeded(id) }
        PasteStack.shared.collect(id)
    }

    private func capture() -> ClipItem? {
        let store = ClipStore.shared

        // Files from Finder & co.
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return ClipItem(kind: .file, fileURLs: paths, contentHash: ClipStore.hash(paths.joined(separator: "\n")))
        }

        // Images (only when there's no meaningful text alongside, e.g. a screenshot or "Copy Image").
        let string = pb.string(forType: .string)
        if string?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true,
           let img = NSImage(pasteboard: pb), let tiff = img.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff), let png = rep.representation(using: .png, properties: [:]) {
            let hash = ClipStore.hash(png)
            let file = store.writeData(png, ext: "png")
            return ClipItem(kind: .image, imageFile: file, imageSize: CGSize(width: rep.pixelsWide, height: rep.pixelsHigh), contentHash: hash)
        }

        guard let text = string, !text.isEmpty else { return nil }
        var item = ClipItem(kind: ClipboardMonitor.classify(text: text), text: text, contentHash: ClipStore.hash(text))
        if item.kind == .text {
            if let rtf = pb.data(forType: .rtf), rtf.count < 5_000_000 { item.rtfFile = store.writeData(rtf, ext: "rtf") }
            if let html = pb.data(forType: .html), html.count < 5_000_000 { item.htmlFile = store.writeData(html, ext: "html") }
        }
        return item
    }

    static func classify(text: String) -> ItemKind {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if isHexColor(t) { return .color }
        if !t.contains(" "), !t.contains("\n"), let url = URL(string: t), let scheme = url.scheme?.lowercased(),
           ["http", "https"].contains(scheme), url.host != nil {
            return .link
        }
        return .text
    }

    static func isHexColor(_ s: String) -> Bool {
        s.range(of: "^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$", options: .regularExpression) != nil
    }
}

/// Paste's own UI sounds (synthesized by scripts/make_sounds.py, bundled in Resources).
enum SoundFX {
    private static func load(_ name: String) -> NSSound? {
        guard let url = Bundle.main.url(forResource: name, withExtension: "wav") else { return nil }
        return NSSound(contentsOf: url, byReference: false)
    }
    private static let copySound = load("Copy")
    private static let pasteSound = load("Paste")

    private static func play(_ s: NSSound?) {
        guard AppSettings.shared.soundEffects, let s else { return }
        s.stop()
        s.play()
    }

    static func copy() { play(copySound) }
    static func paste() { play(pasteSound) }
}
